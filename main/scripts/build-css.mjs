// Compiles styles/tesda-main-screen.css -> public/tesda-main-screen.css.
// The dashboard is a static file in public/, so it can't use Next's CSS pipeline;
// this replaces the Tailwind CDN script (which forced 'unsafe-inline' in the CSP).
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

export const input = fileURLToPath(new URL("../styles/tesda-main-screen.css", import.meta.url));
export const output = fileURLToPath(new URL("../public/tesda-main-screen.css", import.meta.url));

export async function buildCss() {
  const result = await postcss([tailwindcss({ optimize: { minify: true } })])
    .process(await readFile(input, "utf8"), { from: input, to: output });
  return `/* Generated by scripts/build-css.mjs from styles/tesda-main-screen.css. Do not edit. */\n${result.css}`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const css = await buildCss();
  await writeFile(output, css);
  console.log(`Built ${output} (${(css.length / 1024).toFixed(1)} KB)`);
}
